"""Every pip lock is fully hash-pinned and every pip install enforces it."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
LOCKS = [REPO / "scripts" / "requirements-tools.txt",
         REPO / "demo-app" / "requirements.txt",
         REPO / "demo-app" / "requirements-dev.txt"]


def entries(text: str) -> dict[str, list[str]]:
    """package==version -> its hashes (pip-compile layout)."""
    out: dict[str, list[str]] = {}
    current = None
    for line in text.splitlines():
        m = re.match(r"^([A-Za-z0-9_.-]+==[^\s\;]+)", line)
        if m:
            current = m.group(1)
            out[current] = []
        elif current and "--hash=sha256:" in line:
            out[current] += re.findall(r"--hash=sha256:([0-9a-f]{64})", line)
        elif line.strip() and not line.lstrip().startswith(("#", "--hash")):
            current = None
    return out


@pytest.mark.parametrize("lock", LOCKS, ids=lambda p: str(p.relative_to(REPO)))
def test_lock_is_fully_hash_pinned(lock: Path) -> None:
    text = lock.read_text()
    pkgs = entries(text)
    assert pkgs, "no pinned packages found"
    missing = [p for p, hashes in pkgs.items() if not hashes]
    assert not missing, f"packages without hashes: {missing}"
    unpinned = [l for l in text.splitlines()
                if re.match(r"^[A-Za-z0-9_.-]+\s*(>=|<=|~=|>|<|$)", l.strip()) and "==" not in l]
    assert not unpinned, f"unpinned requirement lines: {unpinned}"


@pytest.mark.parametrize("lock", LOCKS, ids=lambda p: str(p.relative_to(REPO)))
def test_lock_has_source_in_file(lock: Path) -> None:
    src = lock.with_suffix(".in")
    assert src.is_file(), f"{lock.name} must be compiled from {src.name}"
    assert "autogenerated by pip-compile" in lock.read_text()[:600]


def test_every_pip_install_requires_hashes() -> None:
    files = list((REPO / ".github" / "workflows").glob("*.yml")) + [REPO / "demo-app" / "Dockerfile"]
    for f in files:
        for line in f.read_text().splitlines():
            if re.search(r"\bpip install\b", line) and not line.lstrip().startswith("#"):
                assert "--require-hashes" in line, f"{f.name}: {line.strip()}"
